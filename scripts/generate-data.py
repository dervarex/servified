#!/usr/bin/env python3
"""
DISCLAIMER: Generated by claude, runs once per minecraft release, not permanent, too lazy to do that manually
----
Turns the output of Mojang's data generator into the name lists servified ships as resources
Only names end up in the repo, never Mojang's actual JSON

Usage:
  java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --all
  python3 scripts/generate-data.py <path to generated/>
"""
import json
import sys
from pathlib import Path

# Registries the client gets as Registry Data (has to match what the client expects)
SYNCED = [
    "dimension_type", "worldgen/biome", "damage_type", "chat_type", "painting_variant",
    "wolf_variant", "wolf_sound_variant", "cat_variant", "cat_sound_variant",
    "pig_variant", "pig_sound_variant", "cow_variant", "cow_sound_variant",
    "chicken_variant", "chicken_sound_variant", "frog_variant", "zombie_nautilus_variant",
    "banner_pattern", "trim_material", "trim_pattern", "enchantment", "jukebox_song",
    "instrument", "dialog", "timeline", "world_clock", "test_environment", "test_instance",
    "sulfur_cube_archetype", "decorated_pot_pattern", "block_transformer",
]

# Built into the game, ids come from reports/registries.json, we only need them for tags
STATIC = ["block", "item", "fluid", "entity_type", "game_event", "point_of_interest_type", "potion"]


def main():
    generated = Path(sys.argv[1]).resolve()

    # works with generated/ and generated/data/minecraft/
    if generated.name == "minecraft" and generated.parent.name == "data":
        generated = generated.parent.parent
    data = generated / "data" / "minecraft"
    out = Path(__file__).resolve().parent.parent / "modules" / "core" / "src" / "main" / "resources"

    entries = {}

    for registry in SYNCED:
        folder = data / registry
        entries[registry] = sorted("minecraft:" + f.relative_to(folder).with_suffix("").as_posix()
                                   for f in folder.rglob("*.json"))

    reports = json.loads((generated / "reports" / "registries.json").read_text())
    for registry in STATIC:
        ids = reports["minecraft:" + registry]["entries"]
        entries[registry] = sorted(ids, key=lambda name: ids[name]["protocol_id"])

    for registry, names in entries.items():
        write(out / "registries" / (registry + ".txt"), names)

    write(out / "registries" / "synced.txt", SYNCED)
    write(out / "registries" / "static.txt", STATIC)

    tagged = []
    for registry, names in entries.items():
        folder = data / "tags" / registry
        if not folder.is_dir():
            continue

        raw = {"minecraft:" + f.relative_to(folder).with_suffix("").as_posix(): json.loads(f.read_text())["values"]
               for f in folder.rglob("*.json")}
        known = set(names)

        lines = []
        for tag in sorted(raw):
            values = [v for v in resolve(tag, raw, set()) if v in known]
            lines.append(" ".join([tag] + values))

        write(out / "tags" / (registry + ".txt"), lines)
        tagged.append(registry)
        print(f"{registry}: {len(names)} entries, {len(raw)} tags")

    write(out / "tags" / "index.txt", tagged)


def resolve(tag, raw, seen):
    """Tags can contain other tags (#minecraft:...), flatten them, keep the order, no duplicates"""
    if tag in seen:
        return []
    seen.add(tag)

    result = []
    for value in raw.get(tag, []):
        if isinstance(value, dict):  # {"id": ..., "required": false}
            value = value["id"]

        for entry in (resolve(value[1:], raw, seen) if value.startswith("#") else [value]):
            if entry not in result:
                result.append(entry)

    return result


def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
